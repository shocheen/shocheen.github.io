#!/usr/bin/env python3
"""Generate Jekyll publication documents from _data/publications.json.

Run with --check to verify generated files without writing them.
No third-party packages are required.
"""
import argparse
import html
import json
import re
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
MARKER = "<!-- Generated by scripts/generate_publications.py; edit _data/publications.json. -->"


def citation(record):
    return (f"{html.escape(record['authors'])}. ({record['year']}). "
            f"{html.escape(record['title'])}. <i>{html.escape(record['venue'])}</i>.")


def validate(records):
    identifiers = set()
    redirects = set()
    for record in records:
        identifier = record["id"]
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}-[a-z0-9-]+", identifier) or identifier in identifiers:
            raise ValueError(f"Invalid or duplicate ID: {identifier}")
        identifiers.add(identifier)
        for field in ("authors", "title", "venue"):
            if not record[field].strip():
                raise ValueError(f"Missing {field}: {identifier}")
        for link in record["links"]:
            parsed = urlparse(link["url"])
            if parsed.scheme not in ("https", "http") or not parsed.netloc or not link["label"]:
                raise ValueError(f"Invalid link: {identifier}: {link}")
        for redirect in record.get("redirect_from", []):
            if not redirect.startswith("/publication/") or redirect in redirects:
                raise ValueError(f"Invalid or duplicate redirect: {redirect}")
            redirects.add(redirect)
    if redirects.intersection(f"/publication/{identifier}" for identifier in identifiers):
        raise ValueError("A redirect overlaps a publication permalink")


def render(record):
    metadata = {
        "title": record["title"], "collection": "publications",
        "permalink": f"/publication/{record['id']}/",
        "date": f"{record['year']}-01-01", "year": record["year"],
        "publication_order": record["order"], "authors": record["authors"],
        "venue": record["venue"], "citation": citation(record), "links": record["links"],
        "source_url": record["source_url"], "source_citation": record["source_citation"],
        "share": False, "comments": False,
    }
    paper = next((link["url"] for link in record["links"] if link["label"] == "pdf"), None)
    if paper:
        metadata["paperurl"] = paper
    if record.get("redirect_from"):
        metadata["redirect_from"] = [url.rstrip("/") + "/" for url in record["redirect_from"]]
    # JSON values are valid YAML and safely preserve colons, quotes and Unicode.
    frontmatter = "\n".join(f"{key}: {json.dumps(value, ensure_ascii=False)}" for key, value in metadata.items())
    return f"---\n{frontmatter}\n---\n\n{MARKER}\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    records = json.loads((ROOT / "_data/publications.json").read_text())
    validate(records)
    expected = {f"{record['id']}.md": render(record) for record in records}
    collection = ROOT / "_publications"
    errors = []
    for filename, content in expected.items():
        path = collection / filename
        if not path.exists() or path.read_text() != content:
            if args.check:
                errors.append(f"Out of date: {filename}")
            else:
                path.write_text(content)
    for path in collection.glob("*.md"):
        if path.name not in expected:
            # Never silently remove unrecognized/custom documents.
            errors.append(f"Extra publication requires review: {path.name}")
    if errors:
        raise SystemExit("\n".join(errors))
    print(f"{'Verified' if args.check else 'Generated'} {len(records)} publications.")


if __name__ == "__main__":
    main()
